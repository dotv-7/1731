"""Public projection reader for the dotv public profile. It never sees the owner's files: the
projection is generated by the owner-side dashboard sync and contains only approved items."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

PROJECTION_FILE = "dotv/public_context.json"
SECTION_MAX = 4000
LOOKUP_MAX = 6000

LOOKUP_SCHEMA = {
    "name": "dotv_public_lookup",
    "description": "Search the owner's PUBLIC documents (approved by the owner for guests). Use it when a guest asks "
                   "about the owner's background, writing or projects. Returns matching sections; empty query lists titles.",
    "parameters": {
        "type": "object",
        "properties": {"query": {"type": "string", "description": "Keywords or a document title"}},
        "required": [],
    },
}


def _home() -> Path:
    try:
        from hermes_constants import get_hermes_home
        return Path(get_hermes_home())
    except Exception:
        return Path(os.environ.get("HERMES_HOME", Path.home() / ".hermes"))


def load_projection(home: Path | None = None) -> dict:
    try:
        data = json.loads(((home or _home()) / PROJECTION_FILE).read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def render_section(projection: dict) -> str:
    facts = [f for f in projection.get("facts") or [] if isinstance(f, str)]
    docs = [d for d in projection.get("documents") or [] if isinstance(d, dict)]
    lines = ["## Owner's public information (approved for guests)"]
    lines += [f"- {f.strip()}" for f in facts] or ["- (nothing has been made public yet)"]
    if docs:
        lines.append("\nPublic documents (read them with dotv_public_lookup):")
        lines += [f"- {d.get('title', '')}" for d in docs]
    text = "\n".join(lines)
    return text if len(text) <= SECTION_MAX else text[: SECTION_MAX - 20] + "\n…(truncated)"


def lookup(projection: dict, query: str = "") -> str:
    docs = [d for d in projection.get("documents") or [] if isinstance(d, dict)]
    if not docs:
        return "No public documents."
    q = (query or "").strip().lower()
    if not q:
        return "Public documents:\n" + "\n".join(f"- {d.get('title', '')}" for d in docs)
    terms = q.split()
    scored = []
    for d in docs:
        hay = f"{d.get('title', '')}\n{d.get('text', '')}".lower()
        score = sum(hay.count(t) for t in terms) + (5 if q in str(d.get("title", "")).lower() else 0)
        if score:
            scored.append((score, d))
    if not scored:
        return "No public document matches that query."
    out, used = [], 0
    for _, d in sorted(scored, key=lambda x: -x[0]):
        chunk = f"### {d.get('title', '')}\n{d.get('text', '')}"
        if used + len(chunk) > LOOKUP_MAX:
            chunk = chunk[: max(0, LOOKUP_MAX - used)]
        out.append(chunk)
        used += len(chunk)
        if used >= LOOKUP_MAX:
            break
    return "\n\n".join(out)


def _handle_lookup(args: dict[str, Any] | None = None, **_: Any) -> str:
    return json.dumps({"result": lookup(load_projection(), (args or {}).get("query", ""))}, ensure_ascii=False)


def register(ctx) -> None:
    ctx.register_system_prompt_section("dotv-public-context", lambda _info: render_section(load_projection()),
                                       max_chars=SECTION_MAX)
    ctx.register_tool(name="dotv_public_lookup", toolset="dotv_public", schema=LOOKUP_SCHEMA,
                      handler=_handle_lookup, description=LOOKUP_SCHEMA["description"], emoji="📖")
